import {chromium} from 'playwright-core';
const out = '/home/vercel-sandbox/proxy/.context';
const browser = await chromium.launch({executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox']});
const page = await browser.newPage({viewport: {width: 1280, height: 900}, deviceScaleFactor: 2});
await page.goto('http://localhost:5173/login');
await page.getByRole('button', {name: 'Log in as dev user'}).click();
await page.waitForURL(/devs-workspace/);
const section = page.locator('section[aria-label="Agents"]');
await section.waitFor();
await page.getByRole('combobox', {name: 'Window'}).click();
await page.getByRole('option', {name: 'Last 24 hours'}).click();
await page.waitForTimeout(800);
await section.screenshot({path: `${out}/fold-home.png`});
await section.getByRole('button', {name: /Show the/}).first().click();
await page.waitForTimeout(400);
await section.screenshot({path: `${out}/fold-home-open.png`});
await page.goto('http://localhost:5173/devs-workspace/activity/tasks/cmvj31y3z02hzp10148jhbu70');
await page.waitForLoadState('networkidle');
await page.waitForTimeout(500);
const box = await page.locator('div.rounded-lg.border').first().boundingBox();
if (box) await page.screenshot({path: `${out}/fold-run.png`, clip: {x: box.x - 8, y: box.y - 8, width: box.width + 16, height: box.height + 16}});
await browser.close();
