import {chromium} from 'playwright-core';
const [link] = process.argv.slice(2);
const browser = await chromium.launch({executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox']});
const page = await browser.newPage({viewport: {width: 1280, height: 900}, deviceScaleFactor: 2});
await page.goto(link.replace('callbackUrl=%2Fagents', 'callbackUrl=%2F'));
await page.waitForLoadState('networkidle');
await page.goto('http://localhost:5173/demo-workspace');
const section = page.locator('section[aria-label="Agents"]');
await section.waitFor();
await page.getByRole('combobox', {name: 'Window'}).click();
await page.getByRole('option', {name: 'Last hour'}).click();
await page.waitForTimeout(600);
const box = await section.boundingBox();
if (!box) throw new Error('no timeline');
await page.mouse.move(box.x + box.width * 0.6, box.y + 120);
const axis = async () => (await page.locator('section[aria-label="Agents"] .tabular-nums span').allInnerTexts()).join(' | ');
console.log('live:', await axis());
for (let i = 0; i < 6; i++) await page.mouse.wheel(-120, 0);
await page.waitForTimeout(900);
console.log('scrolled:', await axis(), '| Now button:', await page.getByRole('button', {name: 'Now'}).count());
const scrollY = await page.evaluate(() => window.scrollY);
await page.mouse.wheel(0, 300);
await page.waitForTimeout(300);
console.log('page scrolls down:', (await page.evaluate(() => window.scrollY)) > scrollY);
await page.evaluate(() => window.scrollTo(0, 0));
await page.waitForTimeout(300);
const top = await section.boundingBox();
if (top) await page.screenshot({path: '/home/vercel-sandbox/proxy/.context/pan.png', clip: {x: top.x - 8, y: top.y - 8, width: top.width + 16, height: 560}});
await page.getByRole('button', {name: 'Now'}).click();
await page.waitForTimeout(400);
console.log('back:', await axis(), '| Now button:', await page.getByRole('button', {name: 'Now'}).count());
await browser.close();
